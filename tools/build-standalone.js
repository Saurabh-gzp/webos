#!/usr/bin/env node
'use strict';
/**
 * build-standalone.js
 * -------------------
 * WebOS ko ek hi self-contained HTML file me pack karta hai:
 *   webos-standalone.html
 *
 * Usme CSS + saare apps inline hote hain, aur public/js/local.js ek
 * client-side backend (filesystem, shell, agent bus) deta hai — isliye
 * file ko double-click karke kholo, kisi preview me daalo, ya GitHub pe
 * upload karo, UI poora chalta hai (server ki zaroorat nahi).
 *
 * Server mode (node server.js) me web proxy, search aur HTTP agent API
 * extra milte hain — wahi "full" assembly hai.
 *
 *   node tools/build-standalone.js
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const PUB = path.join(ROOT, 'public');
const OUT = path.join(ROOT, 'webos-standalone.html');

const read = (p) => fs.readFileSync(p, 'utf8');

/** Inline karte waqt JS ke andar ka </script> HTML ko tod deta hai — escape kar do.
    ("<\/script>" JS me wahi string hai, isliye behaviour bilkul same rehta hai.) */
const escapeForInline = (js) => js
  .replace(/<\/script/gi, '<\\/script')
  .replace(/<!--/g, '<\\!--');

const css = read(path.join(PUB, 'css', 'os.css'));
const kernel = read(path.join(PUB, 'js', 'kernel.js'));
const local = read(path.join(PUB, 'js', 'local.js'));
const APP_FILES = ['browser', 'files', 'editor', 'terminal', 'agentapp', 'misc'];
const apps = APP_FILES
  .map(f => '<script>\n' + escapeForInline(read(path.join(PUB, 'js', 'apps', f + '.js'))) + '\n</script>')
  .join('\n');

const LOCAL_BRIDGE = `
/* local bridge: no server to talk to, so the agent pill shows "local"
   and WebOS.bridge stays API-compatible with the server build. */
(function(){
  if (!window.WEBOS_LOCAL) return;
  function setPill(){
    var p = document.getElementById('agentPill');
    var t = document.getElementById('agentPillText');
    if (p) p.classList.add('on');
    if (t) t.textContent = 'local';
    if (p) p.title = 'Local mode — single-file build. Server deploy karne par live agent API milti hai.';
  }
  document.addEventListener('DOMContentLoaded', function(){ setTimeout(setPill, 900); });
  window.WebOS.bridge = {
    clientId: 'local',
    connected: function(){ return false; },
    history: function(){ return (window.WebOSLocal && WebOSLocal.log() || []).filter(function(e){ return e.kind === 'cmd' || e.kind === 'ok' || e.kind === 'error'; }).slice(-30).map(function(e){ return { op: e.text, ok: e.kind !== 'error', ms: 0, ts: e.ts }; }); },
    reconnect: function(){}
  };
  window.WebOS.isLocal = true;
  /* console se agent ki tarah OS chalane ke liye chhota helper */
  window.agent = function(op, args, app){
    return WebOS.handleCommand({ op: op, args: args || {}, app: app });
  };
})();
`;

let html = read(path.join(PUB, 'index.html'));

// 1. flag + inline CSS
html = html.replace(
  '<link rel="stylesheet" href="/css/os.css">',
  '<style>\n' + css.replace(/<\/style/gi, '<\\/style') + '\n</style>'
);

// 2. remove the server-mode script tags, inject the standalone bundle
html = html.replace(/\s*<script src="\/js\/[^"]+"><\/script>/g, '');

const bundle = `<script>
/* WebOS standalone build — generated by tools/build-standalone.js.
   Do not edit this file: edit public/** and re-run the build script. */
window.WEBOS_LOCAL = true;
</script>
<script>
${escapeForInline(local)}
</script>
<script>
${escapeForInline(kernel)}
</script>
<script>
${escapeForInline(LOCAL_BRIDGE)}
</script>
${apps}`;

//    replacer FUNCTION zaroori hai: replacement string me "$&" / "$`" jaise
//    patterns special hote hain, aur inlined code me wo sequences majood hain.
html = html.replace('<!-- ============ SCRIPTS ============ -->',
  () => '<!-- ============ SCRIPTS (inlined standalone bundle) ============ -->\n' + bundle);

// 3. friendly note in the boot log
html = html.replace("'warming web proxy...'", () => "'local mode: proxy/search ke liye server chalao'");

fs.writeFileSync(OUT, html);

const kb = (Buffer.byteLength(html) / 1024).toFixed(1);
console.log('✓ built ' + path.relative(ROOT, OUT) + '  (' + kb + ' KB, self-contained)');
console.log('  open it directly in a browser, or preview it in the workspace.');
